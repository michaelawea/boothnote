import { describe, it } from 'node:test';
import assert from 'node:assert/strict';

import { parseDecisionWindow as p } from '../window.ts';

/**
 * 决策窗口的解析。**零依赖，一行网络请求都不发。**
 *
 * 这一层最重要的性质不是「认得多」，是**「认不出就说认不出」** ——
 * 一个猜错的日期会把这家客户排到看板上错误的时间段里，
 * 而且没有任何迹象表明它是猜的。所以下面「拒绝」的用例比「认出」的更重要。
 */

describe('决策窗口 → 日期', () => {
  it('完整日期原样认', () => {
    assert.equal(p('2026-12-31'), '2026-12-31');
    assert.equal(p('定在 2026/9/30 之前'), '2026-09-30');
  });

  it('季度取那一季的最后一天 —— 「Q4 前定」的截止是 Q4 结束', () => {
    assert.equal(p('2026 Q4'), '2026-12-31');
    assert.equal(p('Q4 2026 前定供应商'), '2026-12-31');
    assert.equal(p('2026Q1'), '2026-03-31');
    assert.equal(p('2027 年第二季度'), '2027-06-30');
    assert.equal(p('2027年第2季度'), '2027-06-30');
  });

  it('年月取那个月的最后一天', () => {
    assert.equal(p('2026-09'), '2026-09-30');
    assert.equal(p('2026年9月'), '2026-09-30');
    assert.equal(p('2026 年 2 月'), '2026-02-28');
    assert.equal(p('2028年2月'), '2028-02-29', '闰年 2 月是 29 号');
  });

  it('英文月份也认（同事之间英德混着说）', () => {
    assert.equal(p('Sep 2026'), '2026-09-30');
    assert.equal(p('September 2026'), '2026-09-30');
    assert.equal(p('Dec. 2027'), '2027-12-31');
  });

  it('光一个年份 / 车型年 → 落到年底', () => {
    assert.equal(p('2027'), '2027-12-31');
    assert.equal(p('MY2027 已锁'), '2027-12-31');
    assert.equal(p('2027 那款'), '2027-12-31');
  });

  // ── 下面这些比上面重要 ────────────────────────────────────────
  it('🔴 认不出的一律 null —— 猜错的日期比没有日期糟得多', () => {
    for (const bad of [
      '明年年中',
      '快了',
      '看他们什么时候定',
      'ASAP',
      '下个车型年',
      '',
      '   ',
      'Q4', // 没有年份，落不到具体哪一年
      '第三季度', // 同上
    ]) {
      assert.equal(p(bad), null, `「${bad}」不该被解析出日期`);
    }
  });

  it('🔴 离谱的年份不认 —— 转写把「2027」听成「1027」是真会发生的', () => {
    assert.equal(p('1999-01-01'), null);
    assert.equal(p('2199 Q1'), null);
  });

  it('null / undefined 不炸', () => {
    assert.equal(p(null), null);
    assert.equal(p(undefined), null);
  });

  it('月份越界时退回到年底 —— 年份仍然是实打实的信息', () => {
    // 「2026-13」多半是转写把月份听错了，但 2026 这个年份是可信的。
    // 退回年底和「MY2027 → 2027-12-31」是同一条规则：**能确定到哪一层就用哪一层**，
    // 而不是因为月份不可信就把年份也一起扔掉。
    assert.equal(p('2026-13'), '2026-12-31');
    assert.equal(p('2026年0月'), '2026-12-31');
  });
});
