--  速记可修改 + 自动标题（issue #15 · #16）
--
--  维护者 2026-08-05 提的两条，落点都在**派生层**：
--
--    #16「每条速记，可以进去修改」
--    #15「点开 tab 之后，可以查看转录全文，并且可以进行手动的修改」
--
--  🔴 **修改不能落在 `inbox` 上。** 那张表只增不改（§4.2 第 2 条，库里有触发器），
--  因为展会 10 天说过的话是全项目唯一不可再生的资产。人事后觉得
--  「这句转录听错了」而去改原文，等于把当时真正说的那句话弄丢 ——
--  而三个月后没有任何地方能回答「他到底说的是什么」。
--
--  所以一条速记从此有**三层文字**，各自回答一个不同的问题：
--
--    inbox.text        人当时打的字        —— 不可变
--    staging.transcript 机器听出来的       —— 派生，重转写会覆盖
--    staging.edited_text 人事后改定的      —— 派生，人说了算
--
--  显示和喂给 agent 的都用最后一层（有就用），而前两层一个字不动。
--  这和 #14 的 superseded 是同一条判据：**「被取代」不等于「被删掉」。**
-- ════════════════════════════════════════════════════════════════════

-- 人改定的正文。null = 没改过（不是「改成了空」——空字符串才是那个意思）。
alter table staging add column if not exists edited_text text;
alter table staging add column if not exists edited_at   timestamptz;

comment on column staging.edited_text is
  '人在手机上改定的正文（issue #15/#16）。inbox.text 和 transcript 都不动 —— 三层各答一个问题。';

-- ── 自动标题（issue #15）─────────────────────────────────────────────
--
--  「当录音完成之后，自动开始转录，自动生成标题」
--
--  为什么值得单独一列而不是每次现算：列表页一屏十几条，现算意味着
--  十几次模型调用，或者退化成「截前 20 个字」—— 而那正是现在的样子，
--  也正是 维护者 说「让人比较迷」的原因之一。
--
--  ⚠️ 它是**装饰**，不是资产：生成失败就退回首句启发式，永远不阻塞转写。
--  判据和 D61③ 一样 —— 为一个标题把不可再生的录音挡在门外，那才是真事故。
alter table staging add column if not exists title text;

comment on column staging.title is
  '一句话标题（issue #15）。转写完成后生成，失败则退回首句启发式。装饰，不是资产。';
