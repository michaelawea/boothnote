--  对话历史可以删（issue #33 · D102）
--
--  维护者 2026-08-11：「目前 AI Agent 的对话历史仍然无法删除。
--  希望补上对话历史删除功能……删除操作需要有明确确认，避免误删。」
--
--  ── 为什么又是加一列，而不是 delete from thread ────────────────────
--
--  🔴 `thread_message` **只增不改**（migration 002 的 `thread_message_no_update`
--     触发器），而 `thread` 上的外键是 `on delete cascade` ——
--     `delete from thread` 会去级联删 `thread_message`，**当场撞上那个触发器**。
--     真删掉一条对话的唯一办法是先拆掉那道守卫，而那道守卫挡的正是
--     「展会 10 天说过的话」。所以这里和 issue #25 一样：删掉的只是
--     「它出现在我的历史列表里」这件事，不是那些话本身。
--
--  ⚠️ 顺带一条同形状的：`thread_message.inbox_id` 是这条速记「发给过哪几条
--     对话」的**唯一历史依据**（`GET /inbox/:id/threads` 三个来源之一，D95）。
--     真删掉对话，那份历史就跟着没了 —— 于是 #26 那道 double check 会在
--     某些路径上静默失效。软删则完全不受影响：过滤发生在读的那一层。
--
--  ── 这一刀切在哪 ─────────────────────────────────────────────────
--
--  删对话 **只删对话这一层**，另外两个面一个字不动：
--    · 速记页那条原话   —— 照常在（要删它去速记页删，那是 `note_deleted_at`）
--    · CRM 里已入库的行 —— 照常在（要删它去看板删，那是 `record_deleted_at`）
--  三个面各有各的时间戳，可以任意组合 —— 和 migration 012 是同一条判据：
--  **两个独立的动作作用在两个面上时，用两格时间戳，不要一格 + 枚举。**
--
--  这句话必须在确认框上原样说出来。不说的话，人以为「删掉这段对话」
--  会把它整理进 CRM 的那几条也带走，于是不敢删；或者反过来以为带走了，
--  于是不去看板删 —— 两种误解都比没有这个功能更糟。
--
--  ── 恢复靠什么 ───────────────────────────────────────────────────
--
--  纯改一格时间戳。消息、staging、CRM 记录从头到尾没被动过，
--  所以恢复是**无损**的 —— 不像看板删除那样要靠存住一串 Twenty id
--  才回得来（migration 012 的第 ③ 条）。

alter table thread add column if not exists deleted_at timestamptz;
alter table thread add column if not exists deleted_by text;

-- 列表页每次都只读没删的那些。部分索引：删掉的是极少数，
-- 而 `thread_user_idx` 那个全量索引仍然留着（按 id 取单条走主键，用不上它）。
create index if not exists thread_user_live_idx
  on thread (user_id, last_message_at desc) where deleted_at is null;

-- ⚠️ 这一列**不是**「新代码启动时就要用的」（§2.26 的死锁判据）：
--    旧代码不读它，新代码读到 null 就是「没删过」，先起后迁不会死锁。
