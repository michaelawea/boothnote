-- ════════════════════════════════════════════════════════════════════
--  改口重发跨越「已入库」时，把**记录的所有权**带过去（issue #37 · D108）
--
--  维护者 2026-08-11 生产实测：同一条选型情报改了一次口，
--  **CRM 里两版并存**（Movara · Voltaro PowerFlex 3000W 和 2000W 各一条）。
--  而他的意思是「上一句作废，现在是 2000W」，不是「这家有两台逆变器」。
--
--  ── 根因不是「缺自然键」，是作用域停错了层 ──────────────────────────
--
--  🔴 **改口（D90）改的是消息，而人要改的是那条速记入库之后产生的那几条记录。**
--
--  这套系统里**已经有且只有一个**机制在回答「已经入库了，我要改」——
--  D75 的重录：`confirm_payload.recommit` + `twenty_refs` 同时在场时，
--  `confirm.ts` 里每个「建记录」的分支都换成「按存下的 id 更新」
--  （那段注释的原话：**没有任何分支在 redo 下新建已存在的对象**）。
--
--  而改口产生的是一条**全新的 staging**：`twenty_refs` 是空的 → 每个分支都走
--  create → 第二条记录。两个功能各自都「按设计工作」，中间少的是一次交接。
--
--  所以这一列做的事只有一件：**把交接写下来。** 新概念是零个 ——
--  提交那一步复用 D75 已经建好的 redo 路径。
--
--  ── 为什么不是「给 productFitment 加自然键」（issue #37 的 C 案）──────
--
--  ① 它治的不是这个病：重复的成因是所有权没传递，传递之后不会再有第二条。
--  ② 代价正好砍在这套系统最想抓的信号上 —— upsert 会把「这家换过供应商」
--     从两行事实压成一行 + 一段历史文本。
--  ③ 它会静默影响**两条真正独立的速记**（两个人分别记同一家同一品类），
--     而那是「要不要合并」的问题，该由人回答，不该由一次 upsert 悄悄替他回答。
--  维护者 2026-08-11 拍板：按所有权继承做，自然键不做。
--
--  ── 这一列里存什么 ──────────────────────────────────────────────
--
--    {
--      "stagingId":      "被取代的那一版（它现在还拥有那几条记录）",
--      "companyId":      "它入库时定下的客户 —— 用来判断这次客户变没变",
--      "refs":           { …它的 twenty_refs… },
--      "createdRecords": [ {object,id,name}… ],
--      "at":             "记下这次交接的时刻"
--    }
--
--  🔴 **写在「新」那一行上，而不是把老那行清空。** 顺序是承重的：
--     改口之后那一轮**可能永远不会被确认**（人反悔、关掉、换个说法）。
--     如果在改口那一刻就把老行的所有权收走，那几条 CRM 记录会变成**孤儿** ——
--     谁都不拥有它们，看板上删哪一行都删不掉它们。
--     所以：**交接的意向写在改口那一刻，所有权的转移发生在提交成功那一刻。**
--
--  ⚠️ 只继承**最近的那一条已入库**的。同一次改口可能盖住好几版已入库的
--     （人往回改一条很早的消息），而 update-in-place 只能对着一套记录做。
--     其余那些**一个字不动、并且如实报出来**（回包 `otherCommitted`）——
--     「看不见」和「不存在」要分得开。
--
--  ── 客户变了怎么办（维护者 2026-08-11：「这种问题，确实还必须开这一条路」）──
--
--  🔴 **update 路径改不了客户**：`updateProductFitment` / `updateVisit` /
--     `updateSupportCase` 的 patch 里**根本没有 `companyId` 这一项**，
--     D75 的 `requestReconfirm` 也把 companyId 钉死在原来那个上。
--     （这不是疏漏：把一条记录从一家客户挪到另一家，等于改写它的归属，
--       而归属是 D28 的那道闸门。）
--
--     所以「改口顺便改了客户」（Alpin → Rosenfeld 这种）只能是：
--     **把继承来的那几条软删掉（GraphQL delete，可撤销，§2.38）+ 按新客户建新的。**
--     删掉的那几条原样记进老那一行的 `record_deleted_refs` ——
--     于是现成的「撤销看板删除」端点就能把它们捞回来，data-guard 也认得这次下降。

alter table staging add column if not exists replaces jsonb;

-- 谁继承了谁：排查时要能从老那一行反查过来。绝大多数行是 null，用部分索引。
create index if not exists staging_replaces_idx
  on staging ((replaces->>'stagingId')) where replaces is not null;

-- ⚠️ 这一列**不是**「新代码启动时就要用的」（§2.26 的死锁判据）：
--    旧代码不读它，新代码读到 null 就是「这一轮不继承任何东西」。
